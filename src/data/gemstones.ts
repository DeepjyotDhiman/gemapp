// Helper functions for easy querying (mimics Supabase data access layer)
export async function getAllGemstones(): Promise<Gemstone[]> {
  return SAMPLE_GEMSTONES;
}

export async function getGemstoneBySlug(slug: string): Promise<Gemstone | undefined> {
  return SAMPLE_GEMSTONES.find((g) => g.slug === slug);
}

export async function getFeaturedGemstones(): Promise<Gemstone[]> {
  return SAMPLE_GEMSTONES.filter((g) => g.isFeatured).slice(0, 8);
}

export async function getGemstonesByCategory(category: GemstoneCategory): Promise<Gemstone[]> {
  return SAMPLE_GEMSTONES.filter((g) => g.category.toLowerCase() === category.toLowerCase());
}
